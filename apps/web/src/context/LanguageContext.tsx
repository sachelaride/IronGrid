export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [language, setLanguageState] = useState<Language>('PT-BR');

    useEffect(() => {
        const savedLanguage = localStorage.getItem('irongrid_language') as Language;
        if (savedLanguage && ['PT-BR', 'US', 'ES', 'FR', 'DE'].includes(savedLanguage)) {
            setLanguageState(savedLanguage);
        }
    }, []);

    const setLanguage = (lang: Language) => {
        setLanguageState(lang);
        localStorage.setItem('irongrid_language', lang);
    };

    const getLocale = () => {
        switch (language) {
            case 'US': return 'en-US';
            case 'ES': return 'es-ES';
            case 'FR': return 'fr-FR';
            case 'DE': return 'de-DE';
            default: return 'pt-BR';
        }
    };

    const getCurrency = () => {
        switch (language) {
            case 'US': return 'USD';
            case 'ES': return 'EUR';
            case 'FR': return 'EUR';
            case 'DE': return 'EUR';
            default: return 'BRL';
        }
    };

    const t = (key: string) => {
        return translations[language]?.[key] || translations.US?.[key] || translations['PT-BR']?.[key] || key;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, t, getLocale, getCurrency }}>
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (context === undefined) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
}
